/// The header change icon of a file (`getIconForType`).
pub(crate) fn change_icon(kind: ChangeKind) -> &'static [u8] {
    match kind {
        ChangeKind::Modified => MODIFIED,
        ChangeKind::Added => ADDED,
        ChangeKind::Deleted => DELETED,
        ChangeKind::RenamedPure | ChangeKind::RenamedChanged => MOVED,
    }
}

